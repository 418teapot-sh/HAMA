/** 목록 한 줄. sub 가 있으면 그 아래 들여쓴 목록을 붙입니다. */
export type PolicyListItem = string | { text: string; sub: string[] }

/** 조항 본문 한 덩어리: 문단 · 목록 · 표 · Paddle 고지 상자 */
export type PolicyBlock =
  | string
  | { list: PolicyListItem[] }
  | { table: { head: string[]; rows: string[][] } }
  | { notice: string }

export interface PolicyArticle {
  /** 목차에 보이는 이름 (앞 번호는 목차에서 붙임) */
  tocLabel: string
  title: string
  blocks: PolicyBlock[]
}

export interface PolicyDoc {
  key: 'terms' | 'refund' | 'privacy'
  /** 페이지 제목 */
  title: string
  /** 다른 문서 · 푸터 링크에 쓰는 짧은 이름 */
  linkLabel: string
  path: string
  updatedAt: string
  /** 조항 앞 머리말 (개인정보처리방침만) */
  intro?: string
  articles: PolicyArticle[]
}

